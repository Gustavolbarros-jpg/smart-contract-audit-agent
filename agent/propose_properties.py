#!/usr/bin/env python3
"""Write a CVL spec from a contract's shape, with no detector and no LLM.

    SOLC_VERSION=0.8.21 python3 agent/propose_properties.py /caminho/absoluto/X.sol
    SOLC_VERSION=0.8.21 python3 agent/propose_properties.py /caminho/X.sol --verify

`--verify` hands the generated spec to the local Prover (`--compilation_steps_only`), so
the properties are checked against the contract they came from without spending any cloud
quota. On a contract believed correct, every rule should come back Verified: a violation
there is a false alarm from the proposer, not a defect in the contract.
"""

from __future__ import annotations

import argparse
import os
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))

from core.property_proposer import build_spec, propose  # noqa: E402


def main(argv: list[str] | None = None) -> int:
    p = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    p.add_argument("contract", help="caminho absoluto do .sol")
    p.add_argument("--contract-name", default=None, help="nome do contrato dentro do arquivo")
    p.add_argument("--out", default=None, help="onde gravar a spec (padrão: ao lado do contrato)")
    p.add_argument("--verify", action="store_true", help="rodar o verificador local na spec gerada")
    p.add_argument("--timeout", type=int, default=900)
    args = p.parse_args(argv)

    alvo = Path(args.contract).resolve()
    if not alvo.exists():
        print(f"❌ contrato não encontrado: {alvo}")
        return 1
    fonte = alvo.read_text(encoding="utf-8")

    candidatos = propose(fonte, contract=args.contract_name or "")
    if not candidatos:
        print("Nenhuma forma reconhecida: o contrato não credita, não debita e não tem portão de identidade.")
        print("Isso não quer dizer que ele esteja correto — quer dizer que este propositor não tem o que dizer.")
        return 0

    destino = Path(args.out) if args.out else alvo.with_name(f"{alvo.stem}_proposed.spec")
    destino.write_text(
        build_spec(fonte, candidatos, header=f"Generated by agent/propose_properties.py from {alvo.name}.\nNo detector, no LLM. Regenerate instead of editing."),
        encoding="utf-8",
    )

    por_forma: dict[str, int] = {}
    for c in candidatos:
        por_forma[c.shape] = por_forma.get(c.shape, 0) + 1
    print(f"{len(candidatos)} propriedade(s) de {len(por_forma)} forma(s): " +
          ", ".join(f"{k}×{v}" for k, v in sorted(por_forma.items())))
    for c in candidatos:
        print(f"  [{c.shape:13s}] {c.name}")
    print(f"💾 {destino}")

    if not args.verify:
        return 0

    from tools.certora_cli import verify_locally

    nome = args.contract_name or alvo.stem
    print(f"\n🔬 verificador local em {nome} (sem cota)…")
    v = verify_locally(
        contract_path=str(alvo),
        spec_path=str(destino),
        contract_name=nome,
        timeout=args.timeout,
        log_path=str(destino.with_suffix(".log")),
    )
    if not v.conclusive:
        print(f"❌ {v.status}: {(v.detail or '')[:400]}")
        print(f"   log: {destino.with_suffix('.log')}")
        return 2
    for regra, veredito in sorted(v.rules.items()):
        if not regra.endswith("-rule_not_vacuous"):
            marca = "✅" if veredito == "verified" else "🔴"
            print(f"  {marca} {veredito:9s} {regra}")
    if v.violated_rules:
        print(f"\n🔴 {len(v.violated_rules)} violada(s). Num contrato que se acredita correto, isso é alarme falso do propositor.")
    if v.vacuous_rules:
        print(f"⚠️  vácuas (passaram sem serem exercidas): {v.vacuous_rules}")
    if not v.violated_rules and not v.vacuous_rules:
        print("\n✅ todas verificadas e nenhuma vácua.")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
